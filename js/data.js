const UPCOMING_GRADES = ['5급Ⅱ', '5급', '4급Ⅱ', '4급', '3급Ⅱ', '3급', '2급', '1급'];

/* 원시 데이터를 앱에서 쓰기 좋은 모양으로 펼칩니다. */
const HANJA = [];
GRADES.forEach((grade, gi) => {
  grade.start = HANJA.length;
  grade.chars.forEach(([h, m, s, words, ex]) => {
    HANJA.push({
      idx: HANJA.length,
      grade: grade.id,
      gradeName: grade.name,
      gradeIdx: gi,
      h,
      meanings: m.split('/'),
      sounds: s.split('/'),
      words: words.split(';').map((w) => {
        const [word, read, mean] = w.split(',');
        return WORD_NOTES[word] ? { word, read, mean, note: WORD_NOTES[word] } : { word, read, mean };
      }),
      ex,
    });
  });
  grade.end = HANJA.length; // exclusive
});
